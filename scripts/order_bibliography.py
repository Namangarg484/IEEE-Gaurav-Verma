"""Write <out> containing only the bibitems of <pool> that <tex> cites, in order of first citation (IEEE style)."""
import re, sys
tex, pool, out = sys.argv[1:4]
body_tex = open(tex).read()
pool_s = open(pool).read()
inner = pool_s.split("\\begin{thebibliography}{99}", 1)[1].rsplit("\\end{thebibliography}", 1)[0]
entries = {re.match(r"\\bibitem\{([^}]+)\}", e).group(1): e.strip() for e in re.split(r"(?=\\bibitem\{)", inner)[1:]}
order = []
for m in re.finditer(r"\\cite\{([^}]+)\}", body_tex):
    for k in m.group(1).split(","):
        k = k.strip()
        if k not in order:
            order.append(k)
missing = [k for k in order if k not in entries]
if missing:
    sys.exit(f"cited but not in pool: {missing}")
with open(out, "w") as f:
    f.write("% Auto-generated by scripts/order_bibliography.py -- do not edit by hand.\n\\begin{thebibliography}{99}\n\n")
    f.write("\n\n".join(entries[k] for k in order) + "\n\n\\end{thebibliography}\n")
print(f"{len(order)} references written in citation order ({len(entries) - len(order)} unused in pool)")
