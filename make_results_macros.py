"""
make_results_macros.py
======================
Turn results/*.json + results/*.csv into LaTeX macros (results_macros.tex) so the
paper never carries a hand-typed number.

    python make_results_macros.py        # -> results_macros.tex

Macro naming: \\mend<Model><Metric> for the Mendeley LOSO experiment and
\\big<Model><Metric> for the BIG IDEAs within-subject experiment, where
Model in {Mean, Ridge, Demo, RidgeDemo, OneD, TwoD, ThreeD, Fusion} and
Metric in {MAE, RMSE, MARD, Rtwo, R, ZoneA, ZoneAB, Seeds}.  Metrics over
several seeds are written as "mean $\\pm$ std".
"""
