NAMES = {"mean": "Mean", "ridge": "Ridge", "demo": "Demo", "ridge+demo": "RidgeDemo",
         "1d": "OneD", "2d": "TwoD", "3d": "ThreeD", "fusion": "Fusion", "subjmean": "SubjMean",
         "gbm": "Gbm", "gbm+demo": "GbmDemo", "resnet1d": "ResNet", "cnnlstm": "CnnLstm",
         "tod": "Tod", "persist": "Persist",
         "papagei": "Papagei", "anyppg": "Anyppg", "pulseppg": "Pulse"}
METRICS = {"MAE": ("mae", 1), "RMSE": ("rmse", 1), "MARD": ("mard_pct", 1), "Rtwo": ("r2", 2),
           "R": ("pearson_r", 2), "ZoneA": ("zone_A_pct", 1)}


def _fmt(vals, nd):
    vals = [v for v in vals if v is not None and np.isfinite(v)]
    if not vals:
        return "--"
    if len(vals) == 1:
        return f"{vals[0]:.{nd}f}"
    return f"{np.mean(vals):.{nd}f}\\ensuremath{{\\pm}}{np.std(vals):.{nd}f}"


_SEEN: set[str] = set()


def _macro(name, value):
    """One \\newcommand per name; a repeated name (e.g. a cohort-level number
    emitted while iterating models) is written once."""
    assert re.fullmatch(r"[A-Za-z]+", name), name
    if name in _SEEN:
        return ""
    _SEEN.add(name)
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def experiment(summary: dict, prefix_in: str, prefix_out: str) -> str:
    groups: dict[str, list[dict]] = {}
    for tag, m in summary.items():
        if not tag.startswith(prefix_in) or m.get("mae") is None:
            continue
        model = tag[len(prefix_in):].rsplit("_seed", 1)[0]
        groups.setdefault(model, []).append(m)
    out = ""
    for model, runs in groups.items():
        name = macro_model_name(model)
        if name is None:
            continue
        for mname, (key, nd) in METRICS.items():
            out += _macro(f"{prefix_out}{name}{mname}", _fmt([r.get(key) for r in runs], nd))
        out += _macro(f"{prefix_out}{name}ZoneAB",
                      _fmt([r["zone_A_pct"] + r["zone_B_pct"] for r in runs if "zone_B_pct" in r], 1))
        out += _macro(f"{prefix_out}{name}WithinR",
                      _fmt([r.get("within_subject_r_median") for r in runs], 2))
        out += _macro(f"{prefix_out}{name}Seeds", str(len(runs)))
        out += _macro(f"{prefix_out}{name}N", str(runs[0]["n"]))
    return out


def macro_model_name(model: str) -> str | None:
    """'1d' -> 'OneD', '1d_res' -> 'OneDRes'; tags with digits in a suffix
    (e.g. '_cut50') are summarised elsewhere and skipped."""
    base, *suffix = model.split("_")
    if base not in NAMES or any(ch.isdigit() for s in suffix for ch in s):
        return None
    return NAMES[base] + "".join(s.capitalize() for s in suffix)


def dataset_stats(csv_glob: str, prefix: str) -> str:
    files = sorted(glob.glob(csv_glob))
    if not files:
        return ""
    df = pd.read_csv(files[0])
    y = df.y.to_numpy()
    return (_macro(f"{prefix}NRecords", str(len(df))) + _macro(f"{prefix}NSubjects", str(df.subject.nunique()))
            + _macro(f"{prefix}NWindows", str(int(df.n_windows.sum())))
            + _macro(f"{prefix}GlucoseMin", f"{y.min():.0f}") + _macro(f"{prefix}GlucoseMax", f"{y.max():.0f}")
            + _macro(f"{prefix}GlucoseMean", f"{y.mean():.1f}") + _macro(f"{prefix}GlucoseStd", f"{y.std():.1f}"))


